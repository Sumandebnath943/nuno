/** Every character's lines, with ids like `dbz/vegeta:2`. */
export const CHARACTER_TAUNTS: Record<string, Taunt[]> = Object.fromEntries(
  Object.entries(LINES).map(([id, lines]) => [id, lines.map(([text, sound, mood], i) => ({ id: `${id}:${i + 1}`, text, sound, mood }))]),
);

/** The lines of whoever wears this avatar (`img:<character id>`), if they have any. */
export function linesFor(avatar: string | undefined): Taunt[] | undefined {
  return avatar?.startsWith('img:') ? CHARACTER_TAUNTS[avatar.slice(4)] : undefined;
}
